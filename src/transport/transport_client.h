// The Transport Client (requirement 3, design "Transport Client").
//
// Holds the Socket.IO connection to `/ws`: builds the handshake `auth`, reconnects
// with exponential backoff, sends a fresh project context snapshot on every
// connection, surfaces the connection state to the UI, and decides what to do when
// the server refuses a handshake.
//
// Nothing here includes socket.io-client-cpp, websocketpp, asio, or nlohmann/json.
// The library-facing half is `SocketIoConnection`, declared at the bottom of this
// header and defined in transport_client.cpp — the same arrangement as
// `ReaperTransportActionInvoker` in transport_handler.h, and for the same structural
// reason: the suite globs `tests/**/*.cpp` and compiles the logic under test directly
// into the test binary, so logic that lives in a `src/*.cpp` is logic the suite cannot
// reach. Everything in this file runs in the suite with no network, no TLS stack, and
// no Socket.IO client installed.
//
// ---------------------------------------------------------------------------
// Four properties are made structural rather than checked
//
// These are the four things about this component that a comment could not defend,
// so each one is arranged so that the wrong version does not compile or cannot be
// expressed.
//
// **TLS on every outbound connection (requirement 26.3).** `SecureEndpoint` has a
// private constructor and one producer, `secure_endpoint_for_host`, which writes the
// `https://` scheme itself from a literal. A caller cannot supply a scheme — a host
// that already carries one is refused — so there is no argument that could name
// `http`, and no flag to get wrong at connection time. The second half of the
// enforcement is in transport_client.cpp: the pinned client selects TLS at *compile*
// time through `SIO_TLS` and rewrites the scheme of whatever URL it is handed, so
// that translation unit refuses to compile without it. See the comment there — a
// non-TLS build would silently downgrade `https://` to `ws://`, which is exactly the
// failure a runtime check would miss.
//
// **`clientType` and `protocolVersion` are not settable (requirements 3.1, 20.5).**
// They are `static constexpr` members of `HandshakeAuth`, not fields. There is one
// value of each and no constructor argument that could carry a different one. The
// protocol version comes from `transport/schema_bundle_version.h`, generated by CMake
// from the vendored `MANIFEST.json` at configure time — the value belongs to the build
// that was compiled against those schemas, which a runtime read of the manifest would
// not guarantee. That header explains the choice in full.
//
// **A fresh access token in every handshake (requirement 3.2).** `TransportClient`
// has no member of type `secret_string` and no member holding a `HandshakeAuth`. The
// auth is a local inside `attempt_handshake`, constructed from a fresh
// `AccessTokenSource::current_access_token()` call and destroyed when the call
// returns; `HandshakeAuth` is move-only, so it cannot be copied into a member on the
// way past. There is nowhere for a stale token to be kept.
//
//   This is also why the client owns its own reconnection rather than delegating to
//   the Socket.IO client's. The pinned client replays the URL and query string it was
//   first given when it reconnects internally, so an internally-reconnected socket
//   presents the *original* token — precisely the stale handshake requirement 3.2
//   exists to prevent. transport_client.cpp therefore sets the library's reconnect
//   attempts to zero and every attempt originates here.
//
// **Retry once after a token refresh, and only once (requirement 3.6).** This is a
// state, not a counter — `handshake_attempt` — and the bound follows from the shape of
// the transition rather than from remembering to reset something.
// `decide_after_handshake_rejection` is total over the product of the two attempt
// kinds and every rejection, and `attempt_after` is the only route into
// `single_retry_after_token_refresh`: it is produced by exactly one decision, and that
// decision is unreachable *from* `single_retry_after_token_refresh`. So a token
// rejection on the retry cannot decide to retry again, whatever order events arrive
// in, and there is no counter that a forgotten reset could leave at zero. The suite
// asserts it over the whole product rather than over a scenario.
//
// ---------------------------------------------------------------------------
// The rejection vocabulary is the server's, quoted
//
// The codes below are `CONNECTION_REJECTION_CODES` and `AUTHENTICATION_ERROR_CODES`
// from `server/mcp-server/src/components/socket-io-manager.js` and
// `server/mcp-server/src/middleware/jwt-auth.js`. The server attaches them to the
// handshake refusal as `data.code`, which is what the client reads off the Socket.IO
// error packet. They are quoted here rather than paraphrased, and anything
// unrecognised classifies as `unrecognised` and backs off — the safe direction for a
// server whose protocol is ahead of this build.
//
// Two of them, `missing_client_type` and `invalid_client_type`, are unreachable unless
// this build is broken or the server dropped `extension` from its supported list,
// since `clientType` is a compile-time constant here. They are classified distinctly
// so a log line names which, and they back off like anything else — no acceptance
// criterion covers them, and inventing a terminal state for them is not this task's
// to invent. Recorded so the gap is visible.
//
// ---------------------------------------------------------------------------
// One thread, and which one
//
// This class holds no lock and is not thread-safe. It belongs to the network thread,
// which is where the Socket.IO client's callbacks arrive and where the Envelope Codec
// already runs (requirement 4.5) — so `on_connected`, `on_disconnected`,
// `on_handshake_rejected`, and `reconnect_if_due` are all called from there and the
// state has one owner.
//
// That puts `reconnect_if_due` on the network thread rather than on the REAPER timer
// tick, which is worth being explicit about because the tick is where the rest of this
// extension's periodic work happens. Driving it from the tick would mean the main thread
// and the library's io thread both mutating this object, and the reconnection schedule
// is not worth a mutex on the connection state. The only thing that crosses to the main
// thread is the published status, and it crosses the way everything else does: through
// the queue pair, which is what the production `ConnectionStatePresenter` writes to.
// Requirement 2.3 has the Main Thread Dispatcher as the only component that publishes UI
// state to CEF, and this arrangement is what keeps that true.
//
// ---------------------------------------------------------------------------
// The backoff schedule has no jitter, deliberately
//
// `reconnection_delay_for_attempt` is a pure function of the consecutive failure
// count: 500 ms doubling to a 30 second cap. Deterministic, so the suite can state
// monotonicity and the cap as properties rather than sampling a distribution.
//
// The cost is honest and worth writing down: when the server itself goes down, every
// connected extension reconnects on the same schedule, so the recovery is a series of
// synchronised waves rather than a smooth ramp. The 30 second cap is what bounds it —
// in steady state the fan-in is the connected population divided by thirty seconds,
// which is a load the server is sized for. Jitter would smooth the waves and would
// also make the schedule untestable as a property, and nothing in requirement 3
// asks for it. If it is ever wanted, it belongs as a bounded perturbation *of* this
// schedule so that the property still holds.

