	// -----------------------------------------------------------------------
	// The endpoint, and TLS
	// -----------------------------------------------------------------------

	// Written by secure_endpoint_for_host from this literal and nowhere else. See the
	// header comment on why a caller cannot supply a scheme.
	inline constexpr std::string_view secure_url_scheme{"https://"};

	// The Socket.IO *path* — `SOCKET_IO_PATH` in the server's socket-io-manager.js.
	// Not a namespace: the server passes it as engine.io's `path` option and both
	// clients connect to the default namespace underneath it.
	//
	// The trailing slash is load-bearing and is the kind of thing that costs an
	// afternoon. Engine.io normalises its configured path to end in a slash and
	// matches an incoming request with a prefix test, so a request for `/ws?EIO=4`
	// does not match `/ws/` and is answered with a 404 rather than a handshake. The
	// pinned client builds its URL by concatenating the resource it parsed out of the
	// URL it was given with the query string, so the slash has to be in the URL this
	// side produces.
	inline constexpr std::string_view socket_io_path{"/ws/"};

	// TLS's default port, written into the URL explicitly. The pinned client asks
	// websocketpp's URI parser for the port and interpolates whatever it answers, so
	// stating it removes a dependency on that parser's scheme-to-port table for the
	// one value that must not be wrong.
	inline constexpr unsigned short default_tls_port = 443;

	// A URL that cannot name a plaintext transport.
	//
	// The constructor is private and `secure_endpoint_for_host` is its only friend, so
	// every instance was built by the one function that writes the scheme. There is no
	// mutator, so an endpoint cannot be edited into a plaintext one after the fact.
	class SecureEndpoint final {
	public:
		// `https://host:port/ws/` — what the Socket.IO client is handed.
		const std::string& url() const { return url_; }

		const std::string& host() const { return host_; }

		unsigned short port() const { return port_; }

	private:
		SecureEndpoint(std::string url, std::string host, unsigned short port)
			: url_{std::move(url)},
			host_{std::move(host)},
			port_{port}
		{
		}

		friend std::optional<SecureEndpoint> secure_endpoint_for_host(
			std::string_view host,
			unsigned short port
		);

		std::string url_;
		std::string host_;
		unsigned short port_;
	};

	// Whether a character can appear in a host name this side is willing to build a
	// URL from. Deliberately narrow: letters, digits, `-`, `.`, and `_`. A colon, a
	// slash, an at-sign, a space, or a control character is refused rather than
	// escaped, because every one of them is a way to make the resulting URL mean
	// something other than what the caller wrote.
	//
	// IPv6 literals are refused as a consequence, since they need the colons. The
	// extension connects to a named host behind Nginx, so that is a limitation with no
	// use case rather than a gap.
	inline constexpr bool is_permitted_host_character(char character)
	{
		return (character >= 'a' && character <= 'z')
			|| (character >= 'A' && character <= 'Z')
			|| (character >= '0' && character <= '9')
			|| character == '-'
			|| character == '.'
			|| character == '_';
	}

	// The only way to obtain a SecureEndpoint.
	//
	// Empty for a host this function will not build a URL from: empty, port zero, or
	// carrying any character that is not plainly part of a host name — which refuses a
	// scheme (`https://sesh.example` contains `:` and `/`), a path, a userinfo
	// component, and a port smuggled into the host string. The scheme is this
	// function's to write, and the refusal is what keeps that true.
	inline std::optional<SecureEndpoint> secure_endpoint_for_host(
		std::string_view host,
		unsigned short port = default_tls_port
	)
	{
		if (host.empty() || port == 0) {
			return std::nullopt;
		}

		for (const char character : host) {
			if (!is_permitted_host_character(character)) {
				return std::nullopt;
			}
		}

		// A host that is nothing but separators is not a host.
		if (host.front() == '.' || host.back() == '.' || host.front() == '-') {
			return std::nullopt;
		}

		std::string url;

		url.append(secure_url_scheme);
		url.append(host);
		url.push_back(':');
		url.append(std::to_string(port));
		url.append(socket_io_path);

		return SecureEndpoint{std::move(url), std::string{host}, port};
	}

	// -----------------------------------------------------------------------
	// The handshake `auth`
	// -----------------------------------------------------------------------

	// The three field names the server reads off `socket.handshake.auth`. Quoted from
	// the server's own `readHandshakeAuth` and `resolveClientType`, so the two sides
	// do not carry independent spellings of the same contract.
	//
	// `token` rather than `accessToken`: the server reads `handshakeAuth.token`.
	inline constexpr std::string_view handshake_auth_token_field{"token"};
	inline constexpr std::string_view handshake_auth_client_type_field{"clientType"};
	inline constexpr std::string_view handshake_auth_protocol_version_field{"protocolVersion"};

	// One of the server's two `CLIENT_TYPES`. The extension is always this one, which
	// is why it is a constant rather than a field — see the header comment.
	inline constexpr std::string_view extension_client_type{"extension"};

	// What goes into one handshake, and it goes into exactly one.
	//
	// Move-only, so it cannot be copied into a member on its way to the socket. The
	// token is a `secret_string`, so it has no `operator<<`, no implicit conversion to
	// a string, and no Catch2 stringifier — a failing assertion in this suite prints
	// `{?}` rather than a producer's access token into a public CI log.
	class HandshakeAuth final {
	public:
		explicit HandshakeAuth(auth::secret_string access_token)
			: access_token_{std::move(access_token)}
		{
		}

		HandshakeAuth(const HandshakeAuth&) = delete;
		HandshakeAuth& operator=(const HandshakeAuth&) = delete;
		HandshakeAuth(HandshakeAuth&&) = default;
		HandshakeAuth& operator=(HandshakeAuth&&) = delete;

		const auth::secret_string& access_token() const { return access_token_; }

		// Not fields. There is one value of each in this build and no way to supply
		// another — requirements 3.1 and 20.5 held structurally rather than by a call
		// site remembering to pass the right string.
		static constexpr std::string_view client_type() { return extension_client_type; }

		static constexpr std::string_view protocol_version()
		{
			return schema_bundle::protocol_version;
		}

		// What a log line may say about a handshake. Reports the token's length and
		// never its characters, via `secret_string::describe_for_log`.
		std::string describe_for_log() const
		{
			std::string description{handshake_auth_client_type_field};

			description += '=';
			description.append(client_type());
			description += ' ';
			description.append(handshake_auth_protocol_version_field);
			description += '=';
			description.append(protocol_version());
			description += ' ';
			description.append(handshake_auth_token_field);
			description += '=';
			description += access_token_.describe_for_log();

			return description;
		}

	private:
		auth::secret_string access_token_;
	};

	// -----------------------------------------------------------------------
	// Connection state, as the UI sees it
	// -----------------------------------------------------------------------

	// Requirement 3.4's three values, and only those three. "Connecting" is not one of
	// them: an attempt in flight reports `reconnecting`, which is the honest reading
	// for the producer either way — something is being tried and nothing is connected.
	enum class connection_state {
		connected,
		reconnecting,
		disconnected
	};

	inline constexpr std::string_view describe_connection_state(connection_state state)
	{
		switch (state) {
			case connection_state::connected:
				return "connected";
			case connection_state::reconnecting:
				return "reconnecting";
			case connection_state::disconnected:
				return "disconnected";
		}

		return "unknown";
	}

	// Whether the producer has to do something before the extension can reconnect.
	//
	// Separate from `connection_state` because the two answer different questions and
	// collapsing them would give the UI a state it cannot render: `disconnected` alone
	// does not say whether the extension is about to recover on its own.
	enum class producer_action {
		// Nothing to do. Either connected, or reconnecting on its own.
		none,

		// Requirement 3.5. Another REAPER instance holds the session.
		close_the_other_reaper_instance,

		// Requirement 3.6. The token could not be renewed.
		sign_in_again
	};

	inline constexpr std::string_view describe_producer_action(producer_action action)
	{
		switch (action) {
			case producer_action::none:
				return "none";
			case producer_action::close_the_other_reaper_instance:
				return "close_the_other_reaper_instance";
			case producer_action::sign_in_again:
				return "sign_in_again";
		}

		return "unknown";
	}

