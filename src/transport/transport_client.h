	// socket.io-client-cpp behind `SocketConnection`. Defined in
	// transport_client.cpp, which is the one translation unit here that includes the
	// library — and which does not compile on a machine that has not populated it.
	//
	// The client is held through a pointer to a forward-declared type, so this header
	// stays free of sio_client.h. That makes the destructor out-of-line by necessity,
	// which is the usual shape and the same one ReaperTransportActionInvoker uses for
	// the REAPER SDK.
	//
	// The callbacks it installs report into the TransportClient it is given, which is
	// why the reference is a constructor argument rather than a setter: a connection
	// with no reporting target is not constructible.
	class SocketIoConnection final : public SocketConnection {
	public:
		SocketIoConnection();
		~SocketIoConnection() override;

		SocketIoConnection(const SocketIoConnection&) = delete;
		SocketIoConnection& operator=(const SocketIoConnection&) = delete;
		SocketIoConnection(SocketIoConnection&&) = delete;
		SocketIoConnection& operator=(SocketIoConnection&&) = delete;

		// Installs the listeners that report into `client`. Called once, before the
		// first `open`. Separate from the constructor because the client holds this
		// connection and the connection reports to the client, and one of the two has
		// to be constructed first.
		void report_to(TransportClient& client);

		bool open(const SecureEndpoint& endpoint, const HandshakeAuth& handshake_auth) override;

		void close() override;

	private:
		sio::client* client_ = nullptr;
		TransportClient* transport_client_ = nullptr;

		// The rejection code from the last Socket.IO error packet, which arrives on a
		// different listener from the failure notification. See transport_client.cpp.
		std::string last_server_rejection_code_;
	};

